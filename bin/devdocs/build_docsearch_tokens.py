#!/usr/bin/env python3
"""Write the developer-docs DocSearch CSS: design tokens plus the shared rules.

Reads resources/design-tokens/docsearch.json (the single source, also rendered
by resources/views/partials/docsearch-tokens.blade.php for the merchant docs),
then appends resources/design-tokens/docsearch-rules.css (the selector rules the
merchant _search.css @imports) and writes
public/developer/includes/docsearch-tokens.css.

Standard library only. Run from anywhere:
    python3 bin/devdocs/build_docsearch_tokens.py [--out PATH]
"""
import argparse
import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
TOKENS = REPO / "resources" / "design-tokens" / "docsearch.json"
RULES = REPO / "resources" / "design-tokens" / "docsearch-rules.css"
DEFAULT_OUT = REPO / "public" / "developer" / "includes" / "docsearch-tokens.css"

SELECTORS = {"light": ":root", "dark": "html[data-theme=dark]:root"}

HEADER = (
    "/* Generated by bin/devdocs/build_docsearch_tokens.py from\n"
    "   resources/design-tokens/docsearch.json and docsearch-rules.css.\n   Do not edit by hand. */\n"
)


def render(tokens, rules):
    parts = [HEADER]
    for mode, selector in SELECTORS.items():
        parts.append(selector + " {\n")
        for name, value in tokens[mode].items():
            parts.append("    %s: %s;\n" % (name, value))
        parts.append("}\n")
    parts.append("\n")
    parts.append(rules)
    return "".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    args.out.write_text(render(tokens, RULES.read_text(encoding="utf-8")), encoding="utf-8")
    print("wrote %s" % args.out)


if __name__ == "__main__":
    main()
